def generate_plan(data):

    age = int(data["age"])
    activity = data["activity"]
    goal = data["goal"]
    income = data["income"]
    name = data["name"]

    text = (
        f"🧠 <b>Персональный разбор для {name}</b>\n\n"

        f"👤 <b>Возраст:</b> {age}\n"
        f"💼 <b>Чем занимаешься:</b> {activity}\n"
        f"🎯 <b>Цель:</b> {goal}\n"
        f"💰 <b>Желаемый доход:</b> {income}\n\n"

        "━━━━━━━━━━━━━━━━━━━━━━\n"
        "📊 <b>Мой анализ</b>\n"
        "━━━━━━━━━━━━━━━━━━━━━━\n\n"
    )

    # Возраст
    if age < 18:
        text += (
            "📚 Сейчас самое выгодное время инвестировать в свои навыки.\n\n"
        )
    elif age <= 25:
        text += (
            "🚀 Ты находишься в лучшем возрасте для быстрого роста дохода.\n\n"
        )
    else:
        text += (
            "💼 У тебя уже есть жизненный опыт — это огромное преимущество.\n\n"
        )

    # Деятельность
    if "Работаю" in activity:
        text += (
            "💼 Не увольняйся, пока новый источник дохода не станет стабильным.\n\n"
        )

    elif "Учусь" in activity:
        text += (
            "🎓 Начинай зарабатывать уже во время учебы — это даст большое преимущество.\n\n"
        )

    else:
        text += (
            "🔥 Сейчас у тебя есть возможность полностью сосредоточиться на развитии.\n\n"
        )

    # Цель
    if "ИИ" in goal:
        text += (
            "🤖 AI — одно из самых перспективных направлений на ближайшие годы.\n\n"
        )

    elif "бизнес" in goal.lower():
        text += (
            "📈 Лучший путь для тебя — создавать собственные проекты, а не работать только на других.\n\n"
        )

    elif "зарабатывать" in goal.lower():
        text += (
            "💰 Сначала важно получить первые стабильные деньги, а затем масштабироваться.\n\n"
        )

    # Доход
    if "300" in income:
        text += (
            "👑 Доход 300 000+ ₽ требует построения системы или собственного бизнеса.\n\n"
        )

    elif "100" in income:
        text += (
            "📈 Доход 100–300 тыс. ₽ вполне реален за несколько месяцев системной работы.\n\n"
        )

    else:
        text += (
            "🎯 Первой целью станут стабильные 50–100 тыс. ₽ в месяц.\n\n"
        )

    text += (
        "━━━━━━━━━━━━━━━━━━━━━━\n"
        "📅 <b>Твой план</b>\n"
        "━━━━━━━━━━━━━━━━━━━━━━\n\n"

        "✅ Каждый день уделяй развитию минимум 1 час.\n\n"

        "✅ Освой один навык, который можно продавать.\n\n"

        "✅ Сделай первый проект.\n\n"

        "✅ Получи первого клиента или первые деньги.\n\n"

        "━━━━━━━━━━━━━━━━━━━━━━\n"
        "🔥 <b>Первое задание</b>\n"
        "━━━━━━━━━━━━━━━━━━━━━━\n\n"

        "Сегодня выдели 30 минут и выпиши минимум 10 способов, которыми искусственный интеллект может помочь тебе заработать.\n\n"

        "💪 <b>Главное правило:</b>\n"
        "Не пытайся изменить жизнь за один день.\n"
        "Меняй её маленькими действиями каждый день."
    )

    return text