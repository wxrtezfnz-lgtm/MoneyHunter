def generate_plan(data):

    age = int(data["age"])
    activity = data["activity"]
    goal = data["goal"]
    income = data["income"]
    name = data["name"]

    plan = f"👋 {name}, я изучил твою анкету.\n\n"

    # Возраст
    if age < 18:
        plan += (
            "📚 Сейчас твоя главная задача — получить востребованный навык.\n\n"
        )
    elif age <= 25:
        plan += (
            "🚀 У тебя отличный возраст, чтобы быстро увеличить доход и попробовать разные направления.\n\n"
        )
    else:
        plan += (
            "💼 У тебя уже есть жизненный опыт — это огромное преимущество.\n\n"
        )

    # Чем занимается
    if "Работаю" in activity:
        plan += (
            "💼 Пока не увольняйся. Используй текущую работу как финансовую подушку.\n\n"
        )

    elif "Учусь" in activity:
        plan += (
            "🎓 Совмещай учебу с первыми онлайн-проектами.\n\n"
        )

    else:
        plan += (
            "🔥 Сейчас можно полностью сосредоточиться на новом источнике дохода.\n\n"
        )

    # Цель
    if "ИИ" in goal:
        plan += (
            "🤖 Советую изучить AI-инструменты, автоматизацию и создание Telegram-ботов.\n\n"
        )

    elif "бизнес" in goal.lower():
        plan += (
            "📈 Начинай строить собственный цифровой продукт, а не просто искать работу.\n\n"
        )

    else:
        plan += (
            "💰 Сосредоточься на навыках, которые можно быстро монетизировать.\n\n"
        )

    # Доход
    if "300" in income:
        plan += (
            "👑 Для дохода 300 000+ ₽ потребуется собственный бизнес или масштабирование.\n\n"
        )

    elif "100" in income:
        plan += (
            "📈 Цель 100–300 тыс. ₽ вполне достижима за несколько месяцев при системной работе.\n\n"
        )

    else:
        plan += (
            "🎯 Начнем с первых стабильных 50–100 тыс. ₽ в месяц.\n\n"
        )

    plan += (
        "━━━━━━━━━━━━━━\n"
        "📅 План на ближайшие 30 дней:\n\n"
        "✅ Каждый день уделяй 1–2 часа развитию.\n"
        "✅ Освой один востребованный навык.\n"
        "✅ Сделай первый проект.\n"
        "✅ Получи первые деньги.\n\n"
        "🔥 Это будет только начало. Дальше я составлю для тебя полноценную дорожную карту."
    )

    return plan